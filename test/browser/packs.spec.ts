import { test, expect, type Page } from '@playwright/test'
import { settledAudit } from './settled-audit.ts'

async function onboard(page: Page) {
  await page.goto('/')
  await page.getByText('Create an account', { exact: true }).click()
  const form = page.locator('form[action="/register"]')
  await expect(form.locator('[name="csrf"]')).not.toHaveValue('')
  await form.getByLabel('Email').fill(`packs-${crypto.randomUUID()}@example.invalid`)
  await form.getByLabel('Password', { exact: true }).fill('long-packs-fixture-password')
  await form.getByRole('button', { name: 'Create account' }).click()
  await page.getByLabel('Name', { exact: true }).fill('Synthetic learner')
  await page.getByLabel('Birthday', { exact: true }).fill('2018-03-04')
  await page.getByRole('button', { name: 'Add student', exact: true }).click()
  await page.waitForURL(u => /^\/(students\/|welcome\/ai)/.test(u.pathname)); if (new URL(page.url()).pathname === '/welcome/ai') await page.getByRole('link', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Hey, Synthetic learner/ })).toBeVisible()
  const student = page.url().split('/').at(-1)!
  await page.goto('/settings')
  await page.getByLabel('Which AI').selectOption('openai')
  await page.getByRole('textbox', { name: 'API key', exact: true }).fill('fixture-key')
  await page.getByRole('button', { name: 'Save AI', exact: true }).click()
  await page.waitForURL(u => u.searchParams.has('notice'))
  await expect(page).toHaveURL(/settings\?notice=/)
  return student
}
async function audit(page: Page) {
  await page.evaluate(() => Promise.all(document.getAnimations().filter(a => a.effect?.getComputedTiming().endTime !== Infinity && ((a.effect as KeyframeEffect | null)?.target?.getClientRects().length ?? 0) > 0).map(a => a.finished.catch(() => undefined))))
  expect((await (await settledAudit(page)).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

test('a child asks in their own words, watches it being made, gets a short lesson and checked practice', async ({ page }) => {
  const student = await onboard(page)
  await page.goto(`/students/${student}/parent`)
  await page.getByRole('button', { name: 'Lock and return to student mode' }).click()
  // The lock is a form post; let it finish before opening the next page, or WebKit can cancel it.
  await page.waitForURL(u => !u.pathname.endsWith('/parent'))
  await page.goto(`/students/${student}`)
  const card = page.locator('[data-pack-ask]')
  await expect(card.getByRole('heading', { name: 'What do you want to practise?' })).toBeVisible()
  await audit(page)
  await card.getByLabel('What do you want to practise?').fill('times tables for 7')
  await card.getByRole('button', { name: 'Make my practice' }).click()
  // Progress appears in place; the page never switches to a job screen.
  await expect(card.locator('.pack-steps')).toBeVisible()
  await expect(page).toHaveURL(new RegExp(`/students/${student}$`))
  const start = card.getByRole('link', { name: 'Start with the one-minute lesson' })
  await expect(start).toBeVisible({ timeout: 20000 })
  await expect(card).toContainText('seven times table')
  // The new pack leads the next mission, starting with its lesson.
  await page.reload()
  await expect(page.locator('.mission-hero')).toContainText('Seven times table')
  await expect(page.getByRole('link', { name: 'Start with the one-minute lesson' })).toBeVisible()
  await page.getByRole('link', { name: 'Start with the one-minute lesson' }).click()
  await expect(page.getByText('Sevens show up in every week.')).toBeVisible()
  await expect(page.getByText('What is 7 × 2?')).toBeVisible()
  await audit(page)
  await page.getByRole('button', { name: 'I’m ready, let’s go!' }).click()
  await expect(page).toHaveURL(/\/session\//)
  const question = await page.locator('.question-text').innerText()
  expect(question).toMatch(/7 × \d+/)
  const n = Number(question.match(/7 × (\d+)/)![1])
  if (await page.locator('fieldset.choices').count()) await page.getByRole('radio', { name: new RegExp(`^[A-C] ?${7 * n}$`) }).check()
  else await page.getByRole('textbox', { name: /^(Answer|Your steps)$/ }).fill(String(7 * n))
  await page.getByRole('button', { name: 'Check', exact: true }).click()
  await expect(page.locator('.question-text')).not.toHaveText(question)
  // Back home, the lesson is not offered again.
  await page.goto(`/students/${student}`)
  await expect(page.getByRole('link', { name: 'Start with the one-minute lesson' })).toHaveCount(0)
})

test('a parent can ask to see it first, look over every answer, use it, and undo it', async ({ page }) => {
  const student = await onboard(page)
  await page.goto(`/students/${student}/classes`)
  const zone = page.locator('#practice')
  await expect(zone.getByRole('heading', { name: 'Make practice for anything' })).toBeVisible()
  await zone.getByLabel('What do you want to practise?').fill('12 questions on the seven times table')
  await zone.getByRole('checkbox', { name: 'Show me first' }).check()
  await zone.getByRole('button', { name: 'Make it', exact: true }).click()
  const review = zone.getByRole('link', { name: 'Open it to look it over' })
  await expect(review).toBeVisible({ timeout: 20000 })
  await review.click()
  await expect(page.getByRole('heading', { name: 'Check it, then use it' })).toBeVisible()
  await expect(page.getByText('What is 7 × 8?')).toBeVisible()
  await expect(page.getByText('checked twice', { exact: false })).toBeVisible()
  await audit(page)
  await page.getByRole('button', { name: 'Use this practice' }).click()
  await expect(page.getByRole('heading', { name: 'Ready', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo this practice' }).click()
  await expect(page).toHaveURL(/history\?notice=/)
  await expect(page.getByRole('status').filter({ hasText: /practice is removed/ })).toBeVisible()
})

