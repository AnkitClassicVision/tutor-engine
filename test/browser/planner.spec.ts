test('class cards prefill the drawer, drafts survive, and reduced motion keeps every state correct', async ({ page, browserName }) => {
  const student = await onboard(page)
  await fixtureAi(page)
  await page.goto(`/students/${student}/classes`)
  await page.getByRole('link', { name: 'Change this class', exact: true }).first().click()
  const drawer = page.locator('#planner-drawer')
  await expect(drawer).toBeVisible()
  await expect(page.getByLabel('Ask or change something', { exact: true })).toHaveValue(/Change the Math class/)
  await page.getByLabel('Ask or change something', { exact: true }).fill('Change the Math class: a little easier this week')
  await page.reload()
  await expect(page.locator('#planner-drawer')).toBeVisible()
  await expect(page.getByLabel('Ask or change something', { exact: true })).toHaveValue('Change the Math class: a little easier this week')
  await page.getByRole('button', { name: 'Close planner', exact: true }).click()
  await expect(page.locator('#planner-drawer')).toBeHidden()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Planner', exact: true }).click()
  await expect(page.locator('#planner-drawer')).toBeVisible()
  expect(await page.locator('.planner-panel').evaluate(el => getComputedStyle(el).transitionDuration)).toBe('0s')
  await page.keyboard.press('Escape')
  await expect(page.locator('#planner-drawer')).toBeHidden()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  if (browserName === 'chromium') {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Planner', exact: true }).click()
    await expect(page.locator('#planner-drawer')).toBeVisible()
    expect(await page.locator('main').evaluate(el => (el as any).inert === true)).toBe(true)
    await audit(page)
    await page.screenshot({ path: 'evidence/screenshots/planner-phone-sheet.png', fullPage: false })
    await page.locator('.planner-scrim').click({ position: { x: 10, y: 10 } })
    await expect(page.locator('#planner-drawer')).toBeHidden()
    expect(await page.locator('main').evaluate(el => (el as any).inert === true)).toBe(false)
  }
})

