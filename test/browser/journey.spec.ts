test('submission acknowledges immediately while the upload connection is slow', async ({ page }, info) => {
  const student = await onboard(page)
  await page.goto(`/students/${student}/materials/new`)
  await page.getByLabel('Give it a name').fill('Slow upload')
  await page.getByLabel('Type the page', { exact: true }).fill('1. Add two and two.')
  await page.route(`**/students/${student}/materials`, async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.continue() })
  const elapsed = await page.evaluate(async () => {
    const form = document.querySelector('[data-camera]') as HTMLFormElement, before = performance.now()
    form.requestSubmit()
    await new Promise(requestAnimationFrame)
    const status = document.querySelector('[data-upload-status]')?.textContent || ''
    if (!status.includes('Saving') && !status.includes('Uploaded')) throw new Error('Missing immediate status')
    return performance.now() - before
  })
  expect(elapsed).toBeLessThan(200)
  await expect(page.getByRole('heading', { name: 'Slow upload', exact: true })).toBeVisible()
  await info.attach('interaction-acknowledgment-ms', { body: JSON.stringify({ acknowledgmentMs: elapsed }), contentType: 'application/json' })
})

