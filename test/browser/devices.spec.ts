import { devices } from '../device-fixture.ts'
import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function onboard(page: Page) {
  await page.goto('/')
  await page.getByText('Create an account', { exact: true }).click()
  const form = page.locator('form[action="/register"]')
  await expect(form.locator('[name="csrf"]')).not.toHaveValue('')
  await form.getByLabel('Email').fill(`device-${crypto.randomUUID()}@example.invalid`)
  await form.getByLabel('Password', { exact: true }).fill('long-device-fixture-password')
  await form.getByRole('button', { name: 'Create account' }).click()
  await page.getByLabel('Name', { exact: true }).fill('Synthetic learner')
  await page.getByLabel('Birthday', { exact: true }).fill('2018-03-04')
  await page.getByRole('button', { name: 'Add student', exact: true }).click()
  await page.waitForURL(u => /^\/(students\/|welcome\/ai)/.test(u.pathname)); if (new URL(page.url()).pathname === '/welcome/ai') await page.getByRole('link', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Hey, Synthetic learner/ })).toBeVisible()
  return page.url().split('/').at(-1)!
}

test('simulated camera captures and retakes a school result, switches and releases devices', async ({ page, browserName }) => {
  await devices(page, browserName === 'webkit'); const student = await onboard(page)
  await page.goto(`/students/${student}/school`)
  const form = page.locator('[data-school-result]')
  await form.getByLabel('Test title', { exact: true }).fill('Synthetic camera result')
  await form.getByLabel('Test date', { exact: true }).fill('2026-10-02')
  await form.getByLabel('Points earned').fill('8'); await form.getByLabel('Points possible').fill('10')
  expect(await page.evaluate(() => (window as any).__camera.calls.length)).toBe(0)
  await form.getByRole('button', { name: 'Take a picture', exact: true }).click()
  await expect(form.getByRole('button', { name: 'Capture photo' })).toBeEnabled()
  await form.getByRole('button', { name: 'Switch camera' }).click()
  await expect(form.getByRole('button', { name: 'Capture photo' })).toBeEnabled()
  const calls = await page.evaluate(() => (window as any).__camera.calls)
  expect(calls[0].audio).toBe(false); expect(calls[1].video.facingMode.ideal).toBe('user')
  await form.getByRole('button', { name: 'Capture photo' }).click()
  await expect(form.locator('.page-preview')).toHaveCount(1)
  await expect(form.locator('[data-live-camera]')).toBeHidden()
  expect(await page.evaluate(() => (window as any).__camera.stops)).toBe(2)
  await form.getByRole('button', { name: 'Retake', exact: true }).click()
  await expect(form.getByRole('button', { name: 'Capture photo' })).toBeEnabled()
  await form.getByRole('button', { name: 'Capture photo' }).click()
  await expect(form.locator('.page-preview')).toHaveCount(1)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await form.getByRole('button', { name: 'Save teacher result' }).click()
  await expect(page.getByText('8 / 10', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'View marked pages' }).click()
  await expect(page.locator('img[src^="/uploads/"]')).toHaveCount(1)
})

test('camera denial and late permission preserve the form and close pending capture', async ({ page, browserName }) => {
  await devices(page, browserName === 'webkit'); const student = await onboard(page)
  await page.goto(`/students/${student}/materials/new`)
  await page.getByLabel('Give it a name').fill('Synthetic camera page')
  await page.evaluate(() => { (window as any).__camera.deny = true })
  await page.getByRole('button', { name: 'Take a picture', exact: true }).click()
  await expect(page.locator('[data-camera-status]')).toContainText('denied')
  await expect(page.getByLabel('Give it a name')).toHaveValue('Synthetic camera page')
  await page.evaluate(() => { (window as any).__camera.deny = false; (window as any).__camera.pending = true })
  await page.getByRole('button', { name: 'Take a picture', exact: true }).click()
  await expect(page.locator('[data-live-camera]')).toBeVisible()
  await page.getByRole('button', { name: 'Close camera' }).click()
  await page.evaluate(() => (window as any).__camera.resolve())
  await expect(page.locator('[data-live-camera]')).toBeHidden()
  await expect.poll(() => page.evaluate(() => (window as any).__camera.stops)).toBe(1)
  await expect(page.locator('.page-preview')).toHaveCount(0)
})

test('simulated microphone preserves typed drafts, never auto-sends, handles stop and reads the question', async ({ page, browserName }) => {
  await devices(page, browserName === 'webkit'); const student = await onboard(page)
  await page.getByRole('button', { name: 'Let’s go' }).click()
  const form = page.locator('form.answer'), field = form.getByLabel('Answer', { exact: true })
  await field.fill('My answer is')
  let submitted = 0; page.on('request', r => { if (r.method() === 'POST' && /\/answer$/.test(new URL(r.url()).pathname)) submitted++ })
  await form.getByRole('button', { name: 'Use microphone' }).click()
  await expect(form.locator('[data-voice-status]')).toContainText('Listening')
  await expect(form.getByRole('button', { name: 'Stop microphone' })).toHaveClass(/listening/); await expect(form.locator('[data-voice-wave]')).toBeVisible()
  await page.evaluate(() => (window as any).__voice.at(-1).onresult({ results: [{ 0: { transcript: 'fo' }, isFinal: false }] }))
  await expect(field).toHaveValue('My answer is fo'); await expect(form.locator('[data-voice-status]')).toContainText('Listening')
  await page.evaluate(() => { const heard = (window as any).__voice.at(-1); heard.onresult({ results: [{ 0: { transcript: 'four' }, isFinal: true }] }); heard.onend() })
  await expect(field).toHaveValue('My answer is four'); expect(submitted).toBe(0)
  await expect(form.getByRole('button', { name: 'Stop microphone' })).toBeVisible()
  await form.getByRole('button', { name: 'Stop microphone' }).click(); await expect(form.locator('[data-voice-wave]')).toBeHidden()
  await expect(field).toHaveValue('My answer is four')
  await page.reload(); await expect(field).toHaveValue('My answer is four')
  await form.getByRole('button', { name: 'Use microphone' }).click()
  await form.getByRole('button', { name: 'Stop microphone' }).click()
  expect(await page.evaluate(() => (window as any).__voice.at(-1).aborted)).toBe(true)
  const question = await page.locator('.question-text').textContent()
  await page.getByRole('button', { name: 'Read aloud', exact: true }).click()
  expect(await page.evaluate(() => (window as any).__spoken.at(-1))).toBe(question)
  await page.getByRole('button', { name: 'Stop reading' }).click()
  await form.getByRole('button', { name: 'Use microphone' }).click()
  await page.evaluate(() => (window as any).__voice.at(-1).onerror({ error: 'not-allowed' }))
  await expect(form.locator('[data-voice-status]')).toContainText('denied')
  await expect(field).toHaveValue('My answer is four'); expect(submitted).toBe(0)
  await page.goto(`/students/${student}/parent?talk=new#learning-plan`)
  const planning = page.locator('form.planner-form'); await expect(planning.getByRole('button', { name: 'Use microphone' })).toBeVisible()
  await expect(planning.getByLabel('Ask or change something', { exact: true })).toHaveValue('Add a class called ')
})
